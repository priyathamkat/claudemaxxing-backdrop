// Copies the mod's scene out of its hooks module into src/scene.ts, so the video always
// shows exactly what the mod draws. Usage: node sync-scene.mjs [path to register.tsx]
import { readFileSync, writeFileSync } from 'node:fs'

const from = process.argv[2] ?? new URL('../hooks/register.tsx', import.meta.url).pathname
const line = readFileSync(from, 'utf8')
  .split('\n')
  .find(l => l.startsWith('const SCENE = '))

if (!line) {
  throw new Error(`no "const SCENE = " line in ${from}`)
}

writeFileSync(
  new URL('./src/scene.ts', import.meta.url),
  `// The mod's scene, verbatim. Generated by sync-scene.mjs; do not edit.\nexport ${line}\n`,
)
console.log('scene.ts written from', from)
